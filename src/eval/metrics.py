"""Metrics, and the bootstrap that puts an interval around them.

`docs/MILESTONE_3.md` section 3. Accuracy is not computed anywhere in this
module: with positive rates between 0.36% and 0.71%, predicting "no failure"
scores over 99%, and reporting that number would be a way of not answering the
question. ROC-AUC is available but marked as appendix-only for the same reason --
it is dominated by the true negatives, of which there are hundreds of thousands.

PR-AUC is `average_precision_score`, the step-wise estimator. The trapezoidal
alternative interpolates between operating points that no threshold produces and
is optimistically biased on rare positives.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np
import pandas as pd
from sklearn.metrics import (
    average_precision_score,
    confusion_matrix,
    precision_recall_curve,
    roc_auc_score,
)

#: Bootstrap resamples. Enough that the interval endpoints are stable to the
#: second decimal, which is all that is claimed.
N_BOOTSTRAP = 1000

#: Fixed so a rerun reproduces the same intervals. NumPy does not guarantee
#: stream stability across major versions; requirements.txt pins numpy, and the
#: intervals are reported to two decimals where that does not bite.
BOOTSTRAP_SEED = 20240603

CONFIDENCE = 0.95


@dataclass
class PointMetrics:
    """Metrics at one operating point, plus the threshold-free PR-AUC."""

    component: str
    threshold: float
    true_positive: int
    false_positive: int
    false_negative: int
    true_negative: int
    precision: float
    recall: float
    f1: float
    pr_auc: float
    positive_rate: float
    n_rows: int
    n_positive: int
    roc_auc: float | None = None
    intervals: dict[str, tuple[float, float]] = field(default_factory=dict)

    @property
    def confusion(self) -> str:
        return (
            f"TP {self.true_positive:,}  FP {self.false_positive:,}  "
            f"FN {self.false_negative:,}  TN {self.true_negative:,}"
        )


def safe_divide(numerator: float, denominator: float) -> float:
    """0/0 is reported as NaN, not as 0.0.

    Precision is undefined when a model predicts no positives -- that is the
    majority baseline's situation -- and reporting 0.0 there would be a claim
    about performance rather than an absence of one.
    """
    return float("nan") if denominator == 0 else numerator / denominator


def point_metrics(
    y_true: np.ndarray,
    y_score: np.ndarray,
    threshold: float,
    component: str,
    with_roc: bool = False,
) -> PointMetrics:
    y_true = np.asarray(y_true).astype(int)
    y_score = np.asarray(y_score, dtype=float)
    y_pred = (y_score >= threshold).astype(int)

    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    precision = safe_divide(tp, tp + fp)
    recall = safe_divide(tp, tp + fn)
    f1 = safe_divide(2 * precision * recall, precision + recall) if (
        tp + fp > 0 and tp + fn > 0
    ) else float("nan")

    n_positive = int(y_true.sum())
    return PointMetrics(
        component=component,
        threshold=float(threshold),
        true_positive=int(tp),
        false_positive=int(fp),
        false_negative=int(fn),
        true_negative=int(tn),
        precision=precision,
        recall=recall,
        f1=f1,
        pr_auc=float(average_precision_score(y_true, y_score))
        if n_positive
        else float("nan"),
        positive_rate=n_positive / len(y_true),
        n_rows=len(y_true),
        n_positive=n_positive,
        roc_auc=float(roc_auc_score(y_true, y_score))
        if with_roc and n_positive
        else None,
    )


# ----------------------------------------------------------------------
# Bootstrap at the level of failure events
# ----------------------------------------------------------------------


def event_clusters(
    frame: pd.DataFrame, component: str, failures: pd.DataFrame, horizon: pd.Timedelta
) -> np.ndarray:
    """Assign every row to a resampling cluster.

    Resampling rows independently would treat 24 rows generated by one failure as
    24 independent observations and produce an interval several times too narrow.
    So:

    - A positive row is clustered by the failure event that made it positive --
      the first `component` failure for that machine inside its label window.
      All ~24 rows produced by one event move together.
    - A negative row is clustered by (machine, calendar day). Adjacent hourly
      readings for one machine are near-identical, so a day-block keeps that
      autocorrelation intact instead of pretending each hour is independent.

    Returns an integer cluster id per row.
    """
    when = pd.to_datetime(frame["datetime"]).to_numpy()
    machines = frame["machineID"].to_numpy()
    positive = frame[f"label_{component}"].to_numpy().astype(bool)

    component_failures = failures[failures["failure"] == component]
    by_machine = {
        machine: np.sort(pd.to_datetime(group["datetime"]).to_numpy())
        for machine, group in component_failures.groupby("machineID")
    }

    cluster = np.empty(len(frame), dtype=object)

    # Negatives: machine-day blocks.
    days = pd.to_datetime(frame["datetime"]).dt.floor("D").to_numpy()
    for i in np.flatnonzero(~positive):
        cluster[i] = ("neg", int(machines[i]), days[i])

    # Positives: the first qualifying failure event in the label window.
    horizon_ns = np.timedelta64(horizon)
    for i in np.flatnonzero(positive):
        events = by_machine.get(int(machines[i]))
        if events is None:
            cluster[i] = ("pos-orphan", int(machines[i]), when[i])
            continue
        inside = events[(events > when[i]) & (events <= when[i] + horizon_ns)]
        cluster[i] = (
            ("pos", int(machines[i]), inside[0])
            if len(inside)
            else ("pos-orphan", int(machines[i]), when[i])
        )

    _, codes = np.unique(np.array([str(c) for c in cluster]), return_inverse=True)
    return codes


def bootstrap_intervals(
    y_true: np.ndarray,
    y_score: np.ndarray,
    clusters: np.ndarray,
    threshold: float,
    n_resamples: int = N_BOOTSTRAP,
    seed: int = BOOTSTRAP_SEED,
    confidence: float = CONFIDENCE,
) -> dict[str, tuple[float, float]]:
    """Percentile bootstrap CIs for precision, recall and PR-AUC.

    Clusters are resampled with replacement; rows come along with their cluster.
    """
    y_true = np.asarray(y_true).astype(int)
    y_score = np.asarray(y_score, dtype=float)

    order = np.argsort(clusters, kind="stable")
    sorted_clusters = clusters[order]
    boundaries = np.flatnonzero(np.diff(sorted_clusters)) + 1
    members = np.split(order, boundaries)
    n_clusters = len(members)

    rng = np.random.default_rng(seed)
    precisions, recalls, pr_aucs = [], [], []

    for _ in range(n_resamples):
        picked = rng.integers(0, n_clusters, size=n_clusters)
        index = np.concatenate([members[p] for p in picked])
        truth = y_true[index]
        score = y_score[index]
        if truth.sum() == 0:
            continue
        predicted = (score >= threshold).astype(int)
        tp = int(np.sum((predicted == 1) & (truth == 1)))
        fp = int(np.sum((predicted == 1) & (truth == 0)))
        fn = int(np.sum((predicted == 0) & (truth == 1)))
        precisions.append(safe_divide(tp, tp + fp))
        recalls.append(safe_divide(tp, tp + fn))
        pr_aucs.append(float(average_precision_score(truth, score)))

    alpha = (1 - confidence) / 2

    def interval(values: list[float]) -> tuple[float, float]:
        finite = np.asarray([v for v in values if np.isfinite(v)])
        if finite.size == 0:
            return (float("nan"), float("nan"))
        return (
            float(np.quantile(finite, alpha)),
            float(np.quantile(finite, 1 - alpha)),
        )

    return {
        "precision": interval(precisions),
        "recall": interval(recalls),
        "pr_auc": interval(pr_aucs),
        "n_clusters": (n_clusters, n_clusters),
    }


def pr_curve(y_true: np.ndarray, y_score: np.ndarray):
    precision, recall, thresholds = precision_recall_curve(y_true, y_score)
    return precision, recall, thresholds


def format_interval(point: float, bounds: tuple[float, float]) -> str:
    if not np.isfinite(point):
        return "undefined"
    low, high = bounds
    if not (np.isfinite(low) and np.isfinite(high)):
        return f"{point:.3f}"
    return f"{point:.3f} (95% CI {low:.3f}-{high:.3f})"
