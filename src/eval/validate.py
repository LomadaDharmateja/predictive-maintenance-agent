"""Validation-set evaluation: baselines, metrics, calibration, thresholds, importance.

Everything in `docs/MILESTONE_3.md` sections 1, 3, 4, 5 and 6, on the validation
split. Writes `docs/EVALUATION.md` up to a marker; the test section is appended
later, once, by `src/eval/test_evaluation.py`.

This module must never read the test split, and cannot: `load_features` refuses
without the unlock token, and `tests/test_single_test_split_consumer.py` asserts
by source inspection that this file does not carry one.

Run:  python -m src.eval.validate
"""

from __future__ import annotations

import argparse
import json
import sqlite3
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

from src.eval import calibration as calib
from src.eval import plots
from src.eval.baselines import BASELINE_THRESHOLDS, BASELINES, COMPONENT_BASELINES
from src.eval.datasets import load_val, xy
from src.eval.importance import permutation_importance
from src.eval.metrics import (
    N_BOOTSTRAP,
    bootstrap_intervals,
    event_clusters,
    format_interval,
    point_metrics,
)
from src.eval.thresholds import (
    DEFAULT_COST_RATIO,
    SENSITIVITY_RATIOS,
    cost_curve,
    select_threshold,
    sensitivity_table,
)
from src.features.config import (
    COMPONENTS,
    FEATURE_COLUMNS,
    LABEL_HORIZON,
    PRODUCTION_FAMILY,
)

MODELS_DIR = Path("models")
DB = Path("data/pdm.db")
RESULTS = Path("data/generated/validation_results.json")
EVALUATION = Path("docs/EVALUATION.md")
CALIBRATORS = MODELS_DIR / "calibrators.joblib"

FAMILIES = ("lgbm", "logreg")

#: Everything above this marker is regenerated by `make evaluate`. The test
#: section is appended below it, once. The durable record of how many times the
#: test split has been read lives in build_manifest.json, not here.
TEST_SECTION_MARKER = "<!-- test-evaluation-appended-below -->"


def load_failures() -> pd.DataFrame:
    connection = sqlite3.connect(DB)
    try:
        return pd.read_sql_query(
            "SELECT * FROM failures", connection, parse_dates=["datetime"]
        )
    finally:
        connection.close()


def load_model(component: str, family: str, models_dir: Path = MODELS_DIR):
    path = models_dir / f"{component}_{family}.joblib"
    if not path.exists():
        raise FileNotFoundError(f"{path} not found. Run `make train` first.")
    bundle = joblib.load(path)
    if bundle["feature_columns"] != FEATURE_COLUMNS:
        raise ValueError(
            f"{path} was trained on a different feature set "
            f"({len(bundle['feature_columns'])} columns, now {len(FEATURE_COLUMNS)}). "
            "Retrain: `make train`."
        )
    return bundle


def score_all(frame: pd.DataFrame, component: str, models_dir: Path) -> dict[str, np.ndarray]:
    """Scores from every baseline and every model, on one component."""
    X, _ = xy(frame, component)
    scores = {name: fn(frame) for name, fn in BASELINES.items()}
    scores.update(
        {name: fn(frame, component) for name, fn in COMPONENT_BASELINES.items()}
    )
    for family in FAMILIES:
        bundle = load_model(component, family, models_dir)
        scores[family] = bundle["model"].predict_proba(X.to_numpy(dtype=float))[:, 1]
    return scores


def evaluate(models_dir: Path = MODELS_DIR, quiet: bool = False) -> dict:
    def say(message: str) -> None:
        if not quiet:
            print(message, flush=True)

    frame = load_val()
    failures = load_failures()
    say(f"validation rows: {len(frame):,}")

    results: dict = {"components": {}, "n_bootstrap": N_BOOTSTRAP,
                     "cost_ratio": DEFAULT_COST_RATIO,
                     "production_family": PRODUCTION_FAMILY}
    calibrators: dict = {}

    for component in COMPONENTS:
        say(f"\n=== {component} ===")
        y = frame[f"label_{component}"].to_numpy()
        clusters = event_clusters(frame, component, failures, LABEL_HORIZON)
        scores = score_all(frame, component, models_dir)
        positive_rate = float(y.mean())

        record: dict = {
            "positive_rate": positive_rate,
            "n_rows": int(len(y)),
            "n_positive": int(y.sum()),
            "n_bootstrap_clusters": int(len(np.unique(clusters))),
            "series": {},
        }

        # -- metrics for every baseline and model -------------------------
        for name, score in scores.items():
            threshold = BASELINE_THRESHOLDS.get(name, 0.5)
            if name in FAMILIES:
                choice = select_threshold(y, score, component, DEFAULT_COST_RATIO)
                threshold = choice.threshold
            metrics = point_metrics(y, score, threshold, component, with_roc=True)
            intervals = bootstrap_intervals(y, score, clusters, threshold)
            metrics.intervals = intervals
            record["series"][name] = {
                "threshold": metrics.threshold,
                "precision": metrics.precision,
                "recall": metrics.recall,
                "f1": metrics.f1,
                "pr_auc": metrics.pr_auc,
                "roc_auc": metrics.roc_auc,
                "tp": metrics.true_positive,
                "fp": metrics.false_positive,
                "fn": metrics.false_negative,
                "tn": metrics.true_negative,
                "ci": {k: list(v) for k, v in intervals.items()},
            }
            say(
                f"  {name:<16} PR-AUC {metrics.pr_auc:.4f}  "
                f"P {metrics.precision:.3f}  R {metrics.recall:.3f}  "
                f"thr {metrics.threshold:.4f}"
            )

        # -- thresholds from the cost assumption --------------------------
        # The production family, not whichever model scores best. Thresholds
        # and calibrators have to belong to the model that actually ships.
        primary = scores[PRODUCTION_FAMILY]
        record["thresholds"] = {
            f"{ratio:g}": vars(choice)
            for ratio, choice in zip(
                SENSITIVITY_RATIOS,
                sensitivity_table(y, primary, component, SENSITIVITY_RATIOS),
            )
        }
        curves = {
            ratio: cost_curve(y, primary, ratio) for ratio in SENSITIVITY_RATIOS
        }
        chosen = {
            ratio: record["thresholds"][f"{ratio:g}"]["threshold"]
            for ratio in SENSITIVITY_RATIOS
        }
        plots.cost_curves(curves, chosen, component)

        # -- calibration ---------------------------------------------------
        before = calib.assess(y, primary, component, f"{PRODUCTION_FAMILY} (raw)")
        isotonic = calib.fit_isotonic(y, primary)
        platt = calib.fit_platt(y, primary)
        after_iso = calib.assess(
            y, calib.apply_calibrator(isotonic, primary), component, "isotonic"
        )
        after_platt = calib.assess(
            y, calib.apply_calibrator(platt, primary), component, "Platt"
        )
        calibrators[component] = {"isotonic": isotonic, "platt": platt}
        record["calibration"] = {
            report.method: {
                "brier": report.brier,
                "brier_base_rate": report.brier_base_rate,
                "brier_skill_score": report.brier_skill_score,
                "max_deviation": report.max_deviation,
            }
            for report in (before, after_iso, after_platt)
        }
        say(
            f"  Brier raw {before.brier:.6f}  isotonic {after_iso.brier:.6f}  "
            f"Platt {after_platt.brier:.6f}  (base rate {before.brier_base_rate:.6f})"
        )
        plots.reliability_curves([before, after_iso, after_platt], component)

        # -- permutation importance ----------------------------------------
        bundle = load_model(component, PRODUCTION_FAMILY, models_dir)
        X, _ = xy(frame, component)
        importances = permutation_importance(bundle["model"], X, y)
        record["importance"] = [
            {
                "feature": item.feature,
                "mean_drop": item.mean_drop,
                "low": item.low,
                "high": item.high,
            }
            for item in importances[:10]
        ]
        say("  top features: " + ", ".join(i.feature for i in importances[:4]))

        # -- curves ----------------------------------------------------------
        plots.pr_curves(
            {name: (y, score) for name, score in scores.items()},
            positive_rate,
            component,
        )

        results["components"][component] = record

    RESULTS.parent.mkdir(parents=True, exist_ok=True)
    RESULTS.write_text(json.dumps(results, indent=2, sort_keys=True, default=str) + "\n",
                       encoding="utf-8")
    joblib.dump(calibrators, CALIBRATORS)
    say(f"\nwrote {RESULTS} and {CALIBRATORS}")
    return results


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate on the validation split.")
    parser.add_argument("--models-dir", type=Path, default=MODELS_DIR)
    args = parser.parse_args()
    results = evaluate(args.models_dir)

    from src.eval.report import write_validation_report

    write_validation_report(results, EVALUATION)
    print(f"wrote {EVALUATION}")


if __name__ == "__main__":
    main()
