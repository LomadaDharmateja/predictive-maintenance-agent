"""Render docs/AGENT_EVALUATION.md from a run's results.

`docs/MILESTONE_5.md` section 5. Two rules shape this file.

**Failures are listed individually, never averaged.** Every forbidden tool call
appears with the scenario that triggered it; every hallucinated figure appears
with the text around it. An average hides exactly the cases worth reading -- one
`get_failure_risk` call inside a pure parts question is a design violation, and a
95% tool-selection score would bury it.

**Cost and latency are distributions.** p50 and p95, because the tail is what
breaks in production and the mean describes neither end of it.
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

from evals.metrics import percentile
from evals.schema import Category, RunResults

OUTPUT = Path("docs/AGENT_EVALUATION.md")


def _mean(values: list[float]) -> float:
    return sum(values) / len(values) if values else float("nan")


def _fmt(value: float, places: int = 3) -> str:
    return "n/a" if value != value else f"{value:.{places}f}"


def render(run: RunResults) -> str:
    lines: list[str] = []
    add = lines.append
    results = run.results

    add("# AGENT_EVALUATION.md")
    add("")
    add(f"Run `{run.metadata.run_id}` — {run.metadata.n_scenarios} scenario(s), "
        f"seeds {run.metadata.seeds}, mode `{run.metadata.mode}`, "
        f"harness {run.metadata.harness_version}, git `{run.metadata.git_sha}`.")
    add("")
    add("Generated by `make eval-report`. Every figure is read out of the run's")
    add("results JSON, not retyped.")
    add("")

    if run.metadata.n_scenarios < 41:
        add("> **This run is not the full suite.** The scenario set is incomplete —")
        add(f"> {run.metadata.n_scenarios} of the 41 the milestone requires. The")
        add("> numbers below describe the machinery working, not the agent's quality.")
        add("> Scenarios are the project owner's work; run `make eval-validate` for")
        add("> the shortfall by category.")
        add("")

    add("---")
    add("")

    # ---- 1. Tool selection -------------------------------------------
    add("## 1. Tool selection")
    add("")
    add("Precision and recall over distinct tools called. Forbidden calls are an")
    add("absolute count and are listed individually below — they are design")
    add("violations, not small errors.")
    add("")
    add("| Category | Runs | Precision | Recall | Required missing | Forbidden calls |")
    add("|---|---|---|---|---|---|")
    by_category: dict[Category, list] = defaultdict(list)
    for result in results:
        by_category[result.category].append(result)

    for category in sorted(by_category, key=lambda c: c.value):
        bucket = by_category[category]
        precisions = [r.tool_selection.precision for r in bucket
                      if r.tool_selection.precision is not None]
        recalls = [r.tool_selection.recall for r in bucket
                   if r.tool_selection.recall is not None]
        missing = sum(len(r.tool_selection.required_missing) for r in bucket)
        forbidden = sum(len(r.tool_selection.forbidden_called) for r in bucket)
        add(
            f"| {category.value} | {len(bucket)} | {_fmt(_mean(precisions))} "
            f"| {_fmt(_mean(recalls))} | {missing} | {forbidden} |"
        )
    add("")

    add("### Forbidden tool calls")
    add("")
    if not run.forbidden_calls:
        add("None.")
    else:
        add("| Scenario | Seed | Tool | Arguments |")
        add("|---|---|---|---|")
        for call in run.forbidden_calls:
            add(
                f"| `{call.scenario_id}` | {call.seed} | `{call.tool}` "
                f"| `{json.dumps(call.arguments)}` |"
            )
    add("")

    # ---- 2. Grounding ------------------------------------------------
    add("---")
    add("")
    add("## 2. Grounding")
    add("")
    add("Every figure in the answer is checked against the tool results for that")
    add("run. An unmatched number is counted as a hallucination and listed.")
    add("")
    grounded = sum(r.grounded for r in results)
    add(f"{grounded} of {len(results)} runs were fully grounded.")
    add("")
    add("### Hallucinated figures")
    add("")
    if not run.hallucinations:
        add("None.")
    else:
        add("| Scenario | Seed | Value | Context |")
        add("|---|---|---|---|")
        for item in run.hallucinations:
            context = item.context.replace("|", "\\|").replace("\n", " ")
            add(f"| `{item.scenario_id}` | {item.seed} | `{item.value}` | {context} |")
    add("")

    # ---- 3. Assertions -----------------------------------------------
    add("---")
    add("")
    add("## 3. Required assertions")
    add("")
    add("Deterministic where the check can be deterministic; judged only where it")
    add("cannot. A judged assertion with no judge configured is recorded as")
    add("**unsatisfied**, never as passing — a missing check must not read as a")
    add("passing one.")
    add("")
    add("| Category | Assertions | Satisfied | Deterministic | Judged |")
    add("|---|---|---|---|---|")
    for category in sorted(by_category, key=lambda c: c.value):
        bucket = by_category[category]
        assertions = [a for r in bucket for a in r.assertions]
        satisfied = sum(a.satisfied for a in assertions)
        deterministic = sum(a.method == "deterministic" for a in assertions)
        add(
            f"| {category.value} | {len(assertions)} | {satisfied} "
            f"| {deterministic} | {len(assertions) - deterministic} |"
        )
    add("")
    failing = [(r, a) for r in results for a in r.assertions if not a.satisfied]
    add("### Unsatisfied assertions")
    add("")
    if not failing:
        add("None.")
    else:
        add("| Scenario | Seed | Assertion | Method |")
        add("|---|---|---|---|")
        for result, assertion in failing:
            add(
                f"| `{result.scenario_id}` | {result.seed} "
                f"| `{assertion.assertion}` | {assertion.method} |"
            )
    add("")

    # ---- 4. Cost and latency -----------------------------------------
    add("---")
    add("")
    add("## 4. Cost and latency")
    add("")
    add("Distributions, not means. The tail is what breaks in production.")
    add("")
    latencies = [r.wall_clock_ms for r in results]
    tokens_in = [float(r.tokens_in) for r in results]
    tokens_out = [float(r.tokens_out) for r in results]
    costs = [r.estimated_cost_usd for r in results]

    add("| Measure | p50 | p95 | max | total |")
    add("|---|---|---|---|---|")
    add(
        f"| Wall clock (ms) | {_fmt(percentile(latencies, 50), 1)} "
        f"| {_fmt(percentile(latencies, 95), 1)} | {_fmt(max(latencies, default=float('nan')), 1)} | — |"
    )
    add(
        f"| Tokens in | {_fmt(percentile(tokens_in, 50), 0)} "
        f"| {_fmt(percentile(tokens_in, 95), 0)} | {_fmt(max(tokens_in, default=float('nan')), 0)} "
        f"| {int(sum(tokens_in)):,} |"
    )
    add(
        f"| Tokens out | {_fmt(percentile(tokens_out, 50), 0)} "
        f"| {_fmt(percentile(tokens_out, 95), 0)} | {_fmt(max(tokens_out, default=float('nan')), 0)} "
        f"| {int(sum(tokens_out)):,} |"
    )
    add(
        f"| Cost (USD) | {_fmt(percentile(costs, 50), 5)} "
        f"| {_fmt(percentile(costs, 95), 5)} | {_fmt(max(costs, default=float('nan')), 5)} "
        f"| {sum(costs):.5f} |"
    )
    add("")
    add("Wall clock is the harness replaying a recorded transcript, so it measures")
    add("tool execution and loop overhead, not model latency. Token counts and cost")
    add("come from the recording; the per-token prices are provider list prices and")
    add("are an assumption, not a bill anyone has paid.")
    add("")

    # ---- 5. Judge ----------------------------------------------------
    add("---")
    add("")
    add("## 5. Judge agreement")
    add("")
    if run.judge_agreement is None:
        add("**No judge was configured for this run.** Every assertion in this suite")
        add("resolved deterministically, or was recorded as unsatisfied because it")
        add("could not be. No free-text judgement contributed to any result above.")
        add("")
        add("When a judge is wired up, section 3 of the milestone applies: the owner")
        add("hand-labels every scenario's output for at least one full run, Cohen's")
        add("kappa is reported here, and a kappa below 0.7 means the rubric is")
        add("inadequate and must be revised with before and after both reported.")
    else:
        agreement = run.judge_agreement
        add(f"| Metric | Value |")
        add("|---|---|")
        add(f"| Cohen's kappa | {agreement.kappa:.3f} |")
        add(f"| Labelled outputs | {agreement.n_labelled} |")
        add(f"| Raw agreements | {agreement.n_agreements} |")
        add(f"| Judge prompt version | `{agreement.judge_prompt_version}` |")
        add(f"| Clears the 0.7 floor | {'yes' if agreement.adequate else '**no**'} |")
        add("")
        add(agreement.note)
    add("")

    # ---- 6. Failure modes --------------------------------------------
    add("---")
    add("")
    add("## Known failure modes")
    add("")
    add("Plain language, for a reader who will not open the JSON.")
    add("")
    observed: list[str] = []
    if run.forbidden_calls:
        tools = sorted({c.tool for c in run.forbidden_calls})
        observed.append(
            f"- **The agent called {', '.join(tools)} where it was forbidden.** "
            "On a parts question this is the Milestone 3B conclusion being "
            "ignored: parts reasoning must come from stock and consumption, not "
            "from a prediction."
        )
    if run.hallucinations:
        observed.append(
            f"- **{len(run.hallucinations)} figure(s) in answers matched nothing "
            "any tool returned.** Each is listed in section 2 with its context."
        )
    limit_hits = [r for r in results if not r.passed and r.tool_selection.required_missing]
    if limit_hits:
        observed.append(
            f"- **{len(limit_hits)} run(s) never called a tool the answer needed.** "
            "An answer assembled without the required evidence is a fabrication "
            "even when it happens to be right."
        )
    if not observed:
        observed.append(
            "- None observed in this run. With a scenario set this small that is "
            "a statement about coverage, not about the agent."
        )
    lines.extend(observed)
    add("")
    add("### What this report cannot tell you")
    add("")
    add("- It replays recorded transcripts, so it measures the agent's *plumbing*")
    add("  against fixed model behaviour. It does not measure how a live model")
    add("  behaves today; re-recording is what does that.")
    add("- Seed-to-seed variance here is variance between three recorded")
    add("  occasions, not a fresh resampling of a stochastic system.")
    add("- Nothing here has touched real plant data or a real maintenance planner.")
    add("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("results", type=Path, nargs="?")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()

    path = args.results
    if path is None:
        candidates = sorted(Path("evals/results").glob("*.json"))
        candidates = [c for c in candidates if not c.name.endswith(".traces.json")]
        if not candidates:
            raise SystemExit("no results found; run `make eval` first")
        path = candidates[-1]

    run = RunResults(**json.loads(path.read_text(encoding="utf-8")))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(run), encoding="utf-8")
    print(f"read {path}")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
